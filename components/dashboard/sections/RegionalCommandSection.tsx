import React, { useMemo } from 'react';
import { useNavigate } from 'react-router-dom';
import {
    Building2, Users, DollarSign, ArrowRightLeft, ShieldCheck,
    AlertTriangle, CheckCircle2, ChevronRight, TrendingUp,
    Store, Warehouse, MapPin, Briefcase, ArrowUpRight
} from 'lucide-react';
import { Region, Site, Employee, SaleRecord, PurchaseOrder, TransferRecord } from '../../../types';
import { Country, getCountryProfile } from '../../../utils/localization';
import { formatCompactNumber } from '../../../utils/formatting';
import { useData } from '../../../contexts/DataContext';

interface RegionalCommandSectionProps {
    regions: Region[];
    sites: Site[];
    employees: Employee[];
    allSales: SaleRecord[];
    allOrders: PurchaseOrder[];
    transfers?: TransferRecord[];
    activeCountry: Country;
    currencySymbol: string;
    onSelectRegionLens?: (regionCode: string) => void;
}

export const RegionalCommandSection: React.FC<RegionalCommandSectionProps> = ({
    regions,
    sites,
    employees,
    allSales,
    allOrders,
    transfers = [],
    activeCountry,
    currencySymbol,
    onSelectRegionLens
}) => {
    const navigate = useNavigate();
    const { setActiveRegionCode } = useData();

    // Sovereign country filter: ensure zero cross-border data leakage
    const sovereignRegions = useMemo(() => {
        return (regions || []).filter(r => {
            const rCountry = (r.country || '').toUpperCase();
            if (activeCountry === 'KE') {
                return rCountry === 'KENYA' || rCountry === 'KE';
            }
            if (activeCountry === 'ET') {
                return rCountry === 'ETHIOPIA' || rCountry === 'ET';
            }
            return rCountry === activeCountry;
        });
    }, [regions, activeCountry]);

    // Aggregate regional metrics
    const regionalData = useMemo(() => {
        const now = new Date();
        const currentMonthPrefix = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}`;

        return sovereignRegions.map(region => {
            // Facilities assigned to this region
            const regionSites = sites.filter(s => s.regionCode === region.code || (s as any).region_code === region.code);
            const regionSiteIds = new Set(regionSites.map(s => s.id));

            // Workforce assigned to this region
            const regionEmployees = employees.filter(e => 
                e.regionCode === region.code || 
                (e as any).region_code === region.code ||
                (e.siteId && regionSiteIds.has(e.siteId))
            );

            // Regional Operations and Department Managers
            const regionalManager = employees.find(e => 
                (e.id === region.regional_manager_id) || 
                (e.role === 'regional_operations_manager' && (e.regionCode === region.code || (e as any).region_code === region.code))
            );

            const leads = {
                procurement: regionEmployees.find(e => e.role === 'regional_procurement_manager'),
                finance: regionEmployees.find(e => e.role === 'regional_finance_manager'),
                hr: regionEmployees.find(e => e.role === 'regional_hr_manager'),
                logistics: regionEmployees.find(e => e.role === 'regional_supply_chain_manager') || regionEmployees.find(e => e.role === 'regional_logistics_manager'),
                security: regionEmployees.find(e => e.role === 'regional_security_manager')
            };

            // Sales generated by facilities in this region
            const regionSales = allSales.filter(s => regionSiteIds.has(s.siteId));
            const totalRevenue = regionSales.reduce((acc, curr) => acc + (curr.total || 0), 0);

            // Purchase Orders in this region for current month
            const regionOrders = allOrders.filter(o => 
                o.regionCode === region.code || 
                (o as any).region_code === region.code ||
                (o.siteId && regionSiteIds.has(o.siteId))
            );
            const currentMonthOrders = regionOrders.filter(o => 
                (o.createdAt || o.date || '').startsWith(currentMonthPrefix) &&
                o.status !== 'Cancelled' && o.status !== 'Rejected'
            );
            const monthlySpent = currentMonthOrders.reduce((acc, curr) => acc + (curr.totalAmount || 0), 0);

            // Autonomous vs Escalated PO count
            const autonomousLimit = Number(region.autonomous_po_limit ?? 0);
            const budgetCap = Number(region.monthly_procurement_budget) || 0;
            const autonomousCount = currentMonthOrders.filter(o => (o.totalAmount || 0) <= autonomousLimit).length;
            const escalatedCount = currentMonthOrders.filter(o => (o.totalAmount || 0) > autonomousLimit || o.requiresHqApproval).length;

            const budgetPercent = budgetCap > 0 ? Math.min(100, Math.round((monthlySpent / budgetCap) * 100)) : 0;
            const isNearCap = budgetPercent >= 85 && budgetPercent < 100;
            const isOverBudget = budgetCap > 0 && monthlySpent > budgetCap;

            // Open Transfers
            const openTransfers = transfers.filter(t => 
                (t.sourceRegionCode === region.code || t.destRegionCode === region.code) &&
                t.status !== 'Completed' && t.status !== 'Received' && t.status !== 'Cancelled'
            );

            return {
                region,
                regionSites,
                regionEmployees,
                regionalManager,
                leads,
                totalRevenue,
                monthlySpent,
                budgetCap,
                autonomousLimit,
                autonomousCount,
                escalatedCount,
                budgetPercent,
                isNearCap,
                isOverBudget,
                openTransfersCount: openTransfers.length
            };
        });
    }, [sovereignRegions, sites, employees, allSales, allOrders, transfers]);

    // National Totals
    const totalRegionsCount = regionalData.length;
    const totalBudgetSum = regionalData.reduce((acc, curr) => acc + curr.budgetCap, 0);
    const totalSpentSum = regionalData.reduce((acc, curr) => acc + curr.monthlySpent, 0);
    const totalAutonomousOrders = regionalData.reduce((acc, curr) => acc + curr.autonomousCount, 0);
    const totalEscalatedOrders = regionalData.reduce((acc, curr) => acc + curr.escalatedCount, 0);
    const totalOrdersCount = totalAutonomousOrders + totalEscalatedOrders;
    const autonomyRate = totalOrdersCount > 0 ? Math.round((totalAutonomousOrders / totalOrdersCount) * 100) : 100;

    return (
        <div className="space-y-6">
            {/* Top KPI Deck */}
            <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
                <div className="p-4 bg-[var(--theme-bg-card)] rounded-2xl border border-[var(--theme-border)] shadow-sm">
                    <div className="flex items-center justify-between mb-2">
                        <span className="text-xs font-semibold text-[var(--theme-text-secondary)] uppercase tracking-wider">
                            Active Regions
                        </span>
                        <div className="p-2 rounded-xl bg-[var(--theme-accent)]/10 text-[var(--theme-accent)]">
                            <Building2 size={16} />
                        </div>
                    </div>
                    <div className="text-2xl font-bold tracking-tight text-[var(--theme-text-primary)]">
                        {totalRegionsCount}
                    </div>
                    <p className="text-[11px] text-[var(--theme-text-secondary)] mt-1 font-medium">
                        Autonomous Territorial Hubs in {getCountryProfile(activeCountry).name || activeCountry}
                    </p>
                </div>

                <div className="p-4 bg-[var(--theme-bg-card)] rounded-2xl border border-[var(--theme-border)] shadow-sm">
                    <div className="flex items-center justify-between mb-2">
                        <span className="text-xs font-semibold text-[var(--theme-text-secondary)] uppercase tracking-wider">
                            Regional PO Spend
                        </span>
                        <div className="p-2 rounded-xl bg-emerald-500/10 text-emerald-600 dark:text-emerald-400">
                            <DollarSign size={16} />
                        </div>
                    </div>
                    <div className="text-2xl font-bold tracking-tight text-[var(--theme-text-primary)]">
                        {formatCompactNumber(totalSpentSum, { currency: currencySymbol })}
                    </div>
                    <p className="text-[11px] text-[var(--theme-text-secondary)] mt-1 font-medium">
                        Cap: {totalBudgetSum > 0 ? formatCompactNumber(totalBudgetSum, { currency: currencySymbol }) : 'Dynamic / Uncapped'}
                    </p>
                </div>

                <div className="p-4 bg-[var(--theme-bg-card)] rounded-2xl border border-[var(--theme-border)] shadow-sm">
                    <div className="flex items-center justify-between mb-2">
                        <span className="text-xs font-semibold text-[var(--theme-text-secondary)] uppercase tracking-wider">
                            Autonomy Index
                        </span>
                        <div className="p-2 rounded-xl bg-blue-500/10 text-blue-600 dark:text-blue-400">
                            <ShieldCheck size={16} />
                        </div>
                    </div>
                    <div className="text-2xl font-bold tracking-tight text-[var(--theme-text-primary)]">
                        {autonomyRate}%
                    </div>
                    <p className="text-[11px] text-[var(--theme-text-secondary)] mt-1 font-medium">
                        {totalAutonomousOrders} within limit · {totalEscalatedOrders} escalated to HQ
                    </p>
                </div>

                <div className="p-4 bg-[var(--theme-bg-card)] rounded-2xl border border-[var(--theme-border)] shadow-sm">
                    <div className="flex items-center justify-between mb-2">
                        <span className="text-xs font-semibold text-[var(--theme-text-secondary)] uppercase tracking-wider">
                            Cross-Region Velocity
                        </span>
                        <div className="p-2 rounded-xl bg-indigo-500/10 text-indigo-600 dark:text-indigo-400">
                            <ArrowRightLeft size={16} />
                        </div>
                    </div>
                    <div className="text-2xl font-bold tracking-tight text-[var(--theme-text-primary)]">
                        {transfers.filter(t => t.isInterRegion).length}
                    </div>
                    <p className="text-[11px] text-[var(--theme-text-secondary)] mt-1 font-medium">
                        Inter-Regional Transfers recorded
                    </p>
                </div>
            </div>

            {/* Regional Hubs Grid */}
            <div className="grid grid-cols-1 lg:grid-cols-2 gap-5">
                {regionalData.map(data => {
                    const {
                        region,
                        regionSites,
                        regionEmployees,
                        regionalManager,
                        leads,
                        totalRevenue,
                        monthlySpent,
                        budgetCap,
                        autonomousLimit,
                        budgetPercent,
                        isNearCap,
                        isOverBudget,
                        openTransfersCount
                    } = data;

                    return (
                        <div
                            key={region.code}
                            className="p-5 bg-[var(--theme-bg-card)] rounded-2xl border border-[var(--theme-border)] shadow-sm hover:border-[var(--theme-accent)]/40 transition-colors flex flex-col justify-between"
                        >
                            {/* Region Header */}
                            <div>
                                <div className="flex items-start justify-between gap-3 mb-3">
                                    <div>
                                        <div className="flex items-center gap-2">
                                            <h3 className="text-base font-bold text-[var(--theme-text-primary)]">
                                                {region.name}
                                            </h3>
                                            <span className="text-[10px] font-mono px-2 py-0.5 rounded-md font-semibold uppercase bg-[var(--theme-bg-subtle)] text-[var(--theme-text-secondary)] border border-[var(--theme-border)]">
                                                {region.code}
                                            </span>
                                        </div>
                                        <div className="flex items-center gap-3 text-xs text-[var(--theme-text-secondary)] mt-1">
                                            <span className="flex items-center gap-1 font-medium">
                                                <Store size={13} className="text-[var(--theme-accent)]" />
                                                {regionSites.length} Facilities
                                            </span>
                                            <span className="text-[var(--theme-border)]">•</span>
                                            <span className="flex items-center gap-1 font-medium">
                                                <Users size={13} className="text-[var(--theme-accent)]" />
                                                {regionEmployees.length} Personnel
                                            </span>
                                            {openTransfersCount > 0 && (
                                                <>
                                                    <span className="text-[var(--theme-border)]">•</span>
                                                    <span className="flex items-center gap-1 font-medium text-amber-600 dark:text-amber-400">
                                                        <ArrowRightLeft size={13} />
                                                        {openTransfersCount} Active Transfers
                                                    </span>
                                                </>
                                            )}
                                        </div>
                                    </div>

                                    {/* Action Buttons: Lens & Full Territorial Command Inspection */}
                                    <div className="flex items-center gap-1.5 shrink-0">
                                        <button
                                            type="button"
                                            onClick={() => {
                                                if (onSelectRegionLens) {
                                                    onSelectRegionLens(region.code);
                                                } else {
                                                    setActiveRegionCode(region.code);
                                                }
                                            }}
                                            className="px-2.5 py-1.5 rounded-xl text-xs font-semibold bg-[var(--theme-bg-subtle)] text-[var(--theme-text-secondary)] hover:text-[var(--theme-text-primary)] border border-[var(--theme-border)] transition-colors flex items-center gap-1"
                                            title="Engage Regional Lens"
                                        >
                                            <span>Lens</span>
                                            <ChevronRight size={14} />
                                        </button>

                                        <button
                                            type="button"
                                            onClick={() => navigate(`/regional-ops?regionCode=${region.code}`)}
                                            className="px-3 py-1.5 rounded-xl text-xs font-semibold bg-[var(--theme-accent)] text-white hover:opacity-90 transition-all flex items-center gap-1.5 shadow-sm"
                                            title={`Inspect ${region.name} Regional Command`}
                                        >
                                            <span>Inspect</span>
                                            <ArrowUpRight size={14} />
                                        </button>
                                    </div>
                                </div>

                                {/* Dynamic Spend Progress */}
                                <div className="p-3.5 bg-[var(--theme-bg-subtle)] rounded-xl border border-[var(--theme-border)] mb-4">
                                    <div className="flex items-center justify-between text-xs mb-1.5">
                                        <span className="font-semibold text-[var(--theme-text-secondary)] flex items-center gap-1.5">
                                            <DollarSign size={14} className="text-[var(--theme-accent)]" />
                                            Monthly Spend vs Budget
                                        </span>
                                        <span className="font-mono font-bold text-[var(--theme-text-primary)]">
                                            {formatCompactNumber(monthlySpent, { currency: currencySymbol })}
                                            {budgetCap > 0 && (
                                                <span className="text-[var(--theme-text-secondary)] font-normal">
                                                    {' '}/ {formatCompactNumber(budgetCap, { currency: currencySymbol })}
                                                </span>
                                            )}
                                        </span>
                                    </div>

                                    {budgetCap > 0 ? (
                                        <div className="w-full bg-[var(--theme-border)] h-2 rounded-full overflow-hidden mt-1">
                                            <div
                                                className={`h-full rounded-full transition-all duration-300 ${
                                                    isOverBudget
                                                        ? 'bg-rose-500'
                                                        : isNearCap
                                                            ? 'bg-amber-500'
                                                            : 'bg-[var(--theme-accent)]'
                                                }`}
                                                style={{ width: `${budgetPercent}%` }}
                                            />
                                        </div>
                                    ) : (
                                        <div className="text-[11px] text-[var(--theme-text-secondary)] mt-1 font-medium">
                                            Uncapped dynamic monthly budget
                                        </div>
                                    )}

                                    <div className="flex items-center justify-between text-[11px] text-[var(--theme-text-secondary)] mt-2 pt-2 border-t border-[var(--theme-border)]/60">
                                        <span>Autonomous Cap: <strong className="text-[var(--theme-text-primary)] font-mono">{formatCompactNumber(autonomousLimit, { currency: currencySymbol })}</strong> / PO</span>
                                        <span className="font-medium text-emerald-600 dark:text-emerald-400">
                                            Revenue: {formatCompactNumber(totalRevenue, { currency: currencySymbol })}
                                        </span>
                                    </div>
                                </div>

                                {/* Regional Administration Leadership */}
                                <div className="space-y-2">
                                    <span className="text-[11px] font-bold uppercase tracking-wider text-[var(--theme-text-secondary)]">
                                        Territorial Command
                                    </span>
                                    <div className="grid grid-cols-2 gap-2 text-xs">
                                        <div className="p-2 rounded-lg bg-[var(--theme-bg-subtle)] border border-[var(--theme-border)] flex items-center justify-between">
                                            <span className="text-[var(--theme-text-secondary)]">Regional Mgr:</span>
                                            <span className="font-semibold text-[var(--theme-text-primary)] truncate max-w-[120px]">
                                                {regionalManager?.name || 'Unassigned'}
                                            </span>
                                        </div>
                                        <div className="p-2 rounded-lg bg-[var(--theme-bg-subtle)] border border-[var(--theme-border)] flex items-center justify-between">
                                            <span className="text-[var(--theme-text-secondary)]">Procurement:</span>
                                            <span className="font-semibold text-[var(--theme-text-primary)] truncate max-w-[120px]">
                                                {leads.procurement?.name || 'Unassigned'}
                                            </span>
                                        </div>
                                        <div className="p-2 rounded-lg bg-[var(--theme-bg-subtle)] border border-[var(--theme-border)] flex items-center justify-between">
                                            <span className="text-[var(--theme-text-secondary)]">Finance:</span>
                                            <span className="font-semibold text-[var(--theme-text-primary)] truncate max-w-[120px]">
                                                {leads.finance?.name || 'Unassigned'}
                                            </span>
                                        </div>
                                        <div className="p-2 rounded-lg bg-[var(--theme-bg-subtle)] border border-[var(--theme-border)] flex items-center justify-between">
                                            <span className="text-[var(--theme-text-secondary)]">Logistics:</span>
                                            <span className="font-semibold text-[var(--theme-text-primary)] truncate max-w-[120px]">
                                                {leads.logistics?.name || 'Unassigned'}
                                            </span>
                                        </div>
                                    </div>
                                </div>
                            </div>

                            {/* Facilities Pill Row */}
                            <div className="mt-4 pt-3 border-t border-[var(--theme-border)] flex flex-wrap items-center gap-1.5">
                                <span className="text-[10px] uppercase font-bold text-[var(--theme-text-secondary)] mr-1">
                                    Sites:
                                </span>
                                {regionSites.length > 0 ? (
                                    regionSites.slice(0, 4).map(s => (
                                        <span
                                            key={s.id}
                                            className="text-[11px] px-2 py-0.5 rounded-md bg-[var(--theme-bg-subtle)] border border-[var(--theme-border)] text-[var(--theme-text-primary)] font-medium truncate max-w-[140px]"
                                        >
                                            {s.name}
                                        </span>
                                    ))
                                ) : (
                                    <span className="text-[11px] text-[var(--theme-text-secondary)] italic">
                                        No facilities attached
                                    </span>
                                )}
                                {regionSites.length > 4 && (
                                    <span className="text-[11px] text-[var(--theme-accent)] font-semibold">
                                        +{regionSites.length - 4} more
                                    </span>
                                )}
                            </div>
                        </div>
                    );
                })}
            </div>
        </div>
    );
};
